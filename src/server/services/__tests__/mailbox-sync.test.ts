import { beforeEach, describe, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ account: { findFirst: vi.fn(), findMany: vi.fn(), updateMany: vi.fn() }, member: { findUnique: vi.fn() }, send: vi.fn(), permissions: vi.fn() }))
vi.mock('@/server/db/client', () => ({ prisma: { emailAccount: mocks.account, organizationMember: mocks.member } }))
vi.mock('@/server/inngest/client', () => ({ inngest: { send: mocks.send } }))
vi.mock('@/server/auth/permissions', () => ({ getEffectivePermissions: mocks.permissions }))
import { beginMailboxSync, heartbeatMailboxSync, completeMailboxSync, failMailboxSync, listMailboxSyncHealth, requestMailboxSync, scheduleMailboxSyncs } from '../mailbox-sync'
const row = { id: 'account', organizationId: 'org', userId: 'user', provider: 'gmail', email: 'user@example.invalid', lastSyncAt: null, syncStatus: 'idle', syncRequestedAt: null, syncAttemptAt: null, syncRunId: null, syncError: null }
beforeEach(() => {
  vi.resetAllMocks()
  mocks.account.findFirst.mockResolvedValue(row)
  mocks.account.findMany.mockResolvedValue([row])
  mocks.account.updateMany.mockResolvedValue({ count: 1 })
  mocks.member.findUnique.mockResolvedValue({ userId: 'user' })
  mocks.permissions.mockResolvedValue(new Set(['leads:read', 'leads:write']))
  mocks.send.mockResolvedValue({ ids: ['event'] })
})
describe('mailbox sync lifecycle', () => {
  it('renews only the running lease owned by this job and rejects a superseded worker', async () => {
    await heartbeatMailboxSync('org', 'account', 'run')
    expect(mocks.account.updateMany).toHaveBeenCalledWith({ where: { id: 'account', organizationId: 'org', syncRunId: 'run', syncStatus: 'running' }, data: { syncAttemptAt: expect.any(Date) } })
    mocks.account.updateMany.mockResolvedValue({ count: 0 })
    await expect(heartbeatMailboxSync('org', 'account', 'old-run')).rejects.toMatchObject({ code: 'SYNC_SUPERSEDED' })
  })
  it('queues one account with tenant identity and provider selection', async () => {
    expect(await requestMailboxSync('org', 'user', 'gmail')).toEqual({ accountId: 'account', status: 'queued' })
    expect(mocks.account.findFirst).toHaveBeenCalledWith(expect.objectContaining({ where: { organizationId: 'org', userId: 'user', provider: 'gmail' } }))
    expect(mocks.send).toHaveBeenCalledWith(expect.objectContaining({ name: 'email/sync.requested', data: { accountId: 'account', organizationId: 'org' } }))
  })
  it('does not dispatch when another caller owns a fresh lease', async () => {
    mocks.account.updateMany.mockResolvedValue({ count: 0 })
    mocks.account.findFirst.mockResolvedValue({ ...row, syncStatus: 'running' })
    expect(await requestMailboxSync('org', 'user')).toEqual({ accountId: 'account', status: 'running' })
    expect(mocks.send).not.toHaveBeenCalled()
  })
  it('records a safe failure when enqueue fails without exposing provider errors', async () => {
    mocks.send.mockRejectedValue(new Error('token-secret external error'))
    await expect(requestMailboxSync('org', 'user')).rejects.toThrow('could not be queued')
    const writes = JSON.stringify(mocks.account.updateMany.mock.calls)
    expect(writes).toContain('failed')
    expect(writes).not.toContain('token-secret')
  })
  it('starts scoped to current membership and preserves a retry start time', async () => {
    const startedAt = new Date('2026-11-02T01:00:00Z')
    mocks.account.findFirst.mockResolvedValue({ ...row, syncStatus: 'running', syncRunId: 'run', syncAttemptAt: startedAt })
    expect(await beginMailboxSync('org', 'account', 'run')).toEqual(startedAt)
    expect(mocks.account.updateMany).not.toHaveBeenCalled()
    mocks.member.findUnique.mockResolvedValue(null)
    await expect(beginMailboxSync('org', 'account', 'run')).rejects.toThrow('member')
  })
  it('starts a newly queued run with a fresh checkpoint instead of the previous attempt', async () => {
    const previous = new Date('2026-01-01T00:00:00Z')
    mocks.account.findFirst.mockResolvedValue({ ...row, syncStatus: 'queued', syncRunId: 'new-run', syncAttemptAt: previous })
    const started = await beginMailboxSync('org', 'account', 'new-run')
    expect(started.getTime()).toBeGreaterThan(previous.getTime())
    expect(mocks.account.updateMany).toHaveBeenCalledWith(expect.objectContaining({ data: expect.objectContaining({ syncStatus: 'running', syncAttemptAt: started }) }))
  })
  it('does not start a queued job after the owner loses lead permissions', async () => {
    mocks.permissions.mockResolvedValue(new Set(['leads:read']))
    await expect(beginMailboxSync('org', 'account', 'run')).rejects.toThrow('no longer has lead access')
    expect(mocks.account.updateMany).not.toHaveBeenCalled()
  })
  it('rejects a superseded event and ignores stale completion/failure through the run identity', async () => {
    mocks.account.findFirst.mockResolvedValue({ ...row, syncRunId: 'newer' })
    await expect(beginMailboxSync('org', 'account', 'older')).rejects.toMatchObject({ code: 'SYNC_SUPERSEDED' })
    const start = new Date('2026-11-02T01:00:00Z')
    await completeMailboxSync('org', 'account', 'older', start)
    await failMailboxSync('org', 'account', 'older')
    expect(mocks.account.updateMany).toHaveBeenCalledWith(expect.objectContaining({ where: { id: 'account', organizationId: 'org', syncRunId: 'older' }, data: expect.objectContaining({ lastSyncAt: start, syncStatus: 'healthy', syncError: null }) }))
    expect(mocks.account.updateMany).toHaveBeenCalledWith(expect.objectContaining({ where: { id: 'account', organizationId: 'org', syncRunId: 'older' }, data: expect.objectContaining({ syncStatus: 'failed' }) }))
  })
  it('lists only safe health fields scoped to the signed-in mailbox owner', async () => {
    mocks.account.findMany.mockResolvedValue([{ ...row, accessToken: 'secret', syncStatus: 'failed', syncError: 'untrusted raw detail' }])
    const result = await listMailboxSyncHealth('org', 'user')
    expect(mocks.account.findMany).toHaveBeenCalledWith(expect.objectContaining({ where: { organizationId: 'org', userId: 'user', provider: { in: ['gmail', 'microsoft'] } } }))
    expect(JSON.stringify(result)).not.toContain('secret')
    expect(JSON.stringify(result)).not.toContain('untrusted raw detail')
    expect(result[0].status).toBe('failed')
  })
  it('reports stalled work as failed and never treats placeholder scheduler keys as enabled', async () => {
    vi.stubEnv('INNGEST_EVENT_KEY', 'your-placeholder-event-key')
    vi.stubEnv('INNGEST_SIGNING_KEY', 'placeholder-signing-key')
    mocks.account.findMany.mockResolvedValue([{ ...row, syncStatus: 'running', syncAttemptAt: new Date('2020-01-01') }])
    try {
      const [health] = await listMailboxSyncHealth('org', 'user')
      expect(health.status).toBe('failed')
      expect(health.error).toContain('taking longer than expected')
      expect(health.automatic).toBe(false)
    } finally { vi.unstubAllEnvs() }
  })
  it('does not queue a disconnected mailbox or a departed owner', async () => {
    mocks.account.findFirst.mockResolvedValue(null)
    await expect(requestMailboxSync('org', 'user')).rejects.toThrow('connected email account')
    mocks.account.findFirst.mockResolvedValue(row)
    mocks.member.findUnique.mockResolvedValue(null)
    await expect(requestMailboxSync('org', 'user')).rejects.toThrow('member')
    expect(mocks.send).not.toHaveBeenCalled()
  })
  it('schedules eligible connected mailboxes and excludes users without lead access', async () => {
    await scheduleMailboxSyncs()
    expect(mocks.send).toHaveBeenCalledTimes(1)
    mocks.send.mockClear()
    mocks.permissions.mockResolvedValue(new Set())
    await scheduleMailboxSyncs()
    expect(mocks.send).not.toHaveBeenCalled()
  })
})
