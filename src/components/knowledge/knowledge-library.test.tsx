import { beforeEach, describe, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { KnowledgeLibrary } from './knowledge-library'
const doc = { id: 'doc-1', title: 'Pricing draft', category: 'PRICING', contentText: 'New draft price 200.', revision: 2, sourceName: 'pricing.txt', sourceMime: 'text/plain', publishedTitle: 'Published pricing', publishedCategory: 'PRICING', publishedText: 'Published price 100.', publishedRevision: 1, publishedAt: '2026-11-02T00:00:00Z', receptionistApprovedRevision: null, archivedAt: null }
const ok = (data: unknown) => ({ ok: true, json: async () => ({ data }) } as Response)
beforeEach(() => vi.restoreAllMocks())
describe('KnowledgeLibrary', () => {
  it('reviews published content separately and only approves public use after acknowledgement', async () => {
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([doc])).mockResolvedValueOnce(ok(doc)).mockResolvedValueOnce(ok({ ...doc, receptionistApprovedRevision: 1 }))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'Pricing draft' }))
    expect(await screen.findByLabelText('Document text')).toHaveValue('New draft price 200.')
    expect(screen.getByText('Published price 100.')).toBeInTheDocument()
    expect(screen.getByText(/Unpublished changes/)).toBeInTheDocument()
    const approve = screen.getByRole('button', { name: 'Approve for receptionist' })
    expect(approve).toBeDisabled()
    fireEvent.click(screen.getByLabelText(/I reviewed the published snapshot/))
    fireEvent.click(approve)
    await screen.findByText('Receptionist approved · revision 1')
    expect(request.mock.calls[2][0]).toBe('/api/knowledge/doc-1/publish')
    expect(JSON.parse(request.mock.calls[2][1]?.body as string)).toEqual({ action: 'approve_receptionist', revision: 2, publishedRevision: 1, acknowledged: true })
  })
  it('keeps edited text on save conflicts and requires discard before selecting a different document', async () => {
    const second = { ...doc, id: 'doc-2', title: 'Services' }
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([doc, second])).mockResolvedValueOnce(ok(doc)).mockResolvedValueOnce({ ok: false, status: 409, json: async () => ({ error: { message: 'Document changed. Reload before saving.' } }) } as Response).mockResolvedValueOnce(ok(second))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'Pricing draft' }))
    fireEvent.change(await screen.findByLabelText('Document text'), { target: { value: 'Keep my edits' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save draft' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Reload')
    expect(screen.getByLabelText('Document text')).toHaveValue('Keep my edits')
    fireEvent.click(screen.getByRole('button', { name: 'Services' }))
    expect(request).toHaveBeenCalledTimes(3)
    fireEvent.click(screen.getByRole('button', { name: 'Keep editing' }))
    expect(screen.getByLabelText('Document text')).toHaveValue('Keep my edits')
    fireEvent.click(screen.getByRole('button', { name: 'Services' }))
    fireEvent.click(screen.getByRole('button', { name: 'Discard and continue' }))
    await waitFor(() => expect(request).toHaveBeenCalledTimes(4))
  })
  it('extracts a file into editable text without saving or publishing and retains text if extraction fails', async () => {
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([])).mockResolvedValueOnce(ok({ contentText: 'Extracted services.', sourceName: 'services.pdf', sourceMime: 'application/pdf', warnings: ['Review extracted text.'] })).mockRejectedValueOnce(new Error('Extraction unavailable'))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'New document' }))
    fireEvent.change(screen.getByLabelText('Upload document'), { target: { files: [new File(['pdf'], 'services.pdf', { type: 'application/pdf' })] } })
    await waitFor(() => expect(screen.getByLabelText('Document text')).toHaveValue('Extracted services.'))
    await screen.findByText('Review extracted text.')
    expect(request).toHaveBeenCalledTimes(2)
    expect(request.mock.calls[1][0]).toBe('/api/knowledge/extract')
    fireEvent.change(screen.getByLabelText('Upload document'), { target: { files: [new File(['pdf'], 'bad.pdf', { type: 'application/pdf' })] } })
    await screen.findByRole('alert')
    expect(screen.getByLabelText('Document text')).toHaveValue('Extracted services.')
    expect(request).toHaveBeenCalledTimes(3)
  })
  it('saves a draft before publishing and resets public approval after publication', async () => {
    const initial = { ...doc, revision: 1, publishedRevision: 1, receptionistApprovedRevision: 1 }
    const saved = { ...initial, revision: 2, contentText: 'Reviewed updated price.' }
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([initial])).mockResolvedValueOnce(ok(initial)).mockResolvedValueOnce(ok(saved)).mockResolvedValueOnce(ok({ ...saved, publishedText: saved.contentText, publishedRevision: 2, receptionistApprovedRevision: null }))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'Pricing draft' }))
    fireEvent.change(await screen.findByLabelText('Document text'), { target: { value: saved.contentText } })
    expect(screen.getByRole('button', { name: 'Publish for Airish' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Save draft' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Publish for Airish' })).toBeEnabled())
    fireEvent.click(screen.getByRole('button', { name: 'Publish for Airish' }))
    await screen.findByText('Published revision 2')
    expect(screen.getByRole('button', { name: 'Approve for receptionist' })).toBeDisabled()
    expect(request).toHaveBeenCalledTimes(4)
  })
})

describe('knowledge withdrawal and upload bounds', () => {
  it('revokes public approval and unpublishes using the latest revision without losing unsaved edits', async () => {
    const approved = { ...doc, receptionistApprovedRevision: 1 }
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([approved])).mockResolvedValueOnce(ok(approved)).mockResolvedValueOnce(ok({ ...doc, revision: 3 })).mockResolvedValueOnce(ok({ ...doc, revision: 4, publishedAt: null, receptionistApprovedRevision: null }))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'Pricing draft' }))
    fireEvent.change(await screen.findByLabelText('Document text'), { target: { value: 'Unsaved pricing adjustment' } })
    fireEvent.click(screen.getByRole('button', { name: 'Revoke receptionist approval' }))
    await screen.findByText('Receptionist approval revoked.')
    expect(screen.getByLabelText('Document text')).toHaveValue('Unsaved pricing adjustment')
    expect(JSON.parse(request.mock.calls[2][1]?.body as string)).toEqual({ action: 'revoke_receptionist', revision: 2 })
    fireEvent.click(screen.getByRole('button', { name: 'Unpublish' }))
    await screen.findByText('Document unpublished. It is excluded from AI answers.')
    expect(JSON.parse(request.mock.calls[3][1]?.body as string)).toEqual({ action: 'unpublish', revision: 3 })
    expect(screen.getByLabelText('Document text')).toHaveValue('Unsaved pricing adjustment')
  })
  it('archives a saved document and retains a read-only view', async () => {
    vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([doc])).mockResolvedValueOnce(ok(doc)).mockResolvedValueOnce(ok({ ...doc, revision: 3, archivedAt: '2026-11-02T01:00:00Z', publishedAt: null }))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'Pricing draft' }))
    fireEvent.click(await screen.findByRole('button', { name: 'Archive' }))
    await screen.findByRole('heading', { name: 'Archived document' })
    expect(screen.getByLabelText('Document text')).toBeDisabled()
    expect(screen.queryByRole('button', { name: 'Save draft' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Approve for receptionist' })).not.toBeInTheDocument()
  })
  it('rejects an oversized upload before making an extraction request', async () => {
    const request = vi.spyOn(globalThis, 'fetch').mockResolvedValue(ok([]))
    render(<KnowledgeLibrary />)
    fireEvent.click(await screen.findByRole('button', { name: 'New document' }))
    const file = new File(['x'], 'large.txt', { type: 'text/plain' })
    Object.defineProperty(file, 'size', { value: 2 * 1024 * 1024 + 1 })
    fireEvent.change(screen.getByLabelText('Upload document'), { target: { files: [file] } })
    expect(await screen.findByRole('alert')).toHaveTextContent('2 MB')
    expect(request).toHaveBeenCalledTimes(1)
  })
})

it('limits the suggested upload title to the server title bound', async () => {
  const sourceName = `${'a'.repeat(180)}.txt`
  vi.spyOn(globalThis, 'fetch').mockResolvedValueOnce(ok([])).mockResolvedValueOnce(ok({ contentText: 'Services.', sourceName, sourceMime: 'text/plain', warnings: [] }))
  render(<KnowledgeLibrary />)
  fireEvent.click(await screen.findByRole('button', { name: 'New document' }))
  fireEvent.change(screen.getByLabelText('Upload document'), { target: { files: [new File(['Services.'], sourceName, { type: 'text/plain' })] } })
  await waitFor(() => expect(screen.getByLabelText('Document title')).toHaveValue('a'.repeat(160)))
})
