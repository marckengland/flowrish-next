import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
const submit = vi.hoisted(() => vi.fn())
vi.mock('@/server/actions/forecast', () => ({ submitForecast: submit }))
import { CommitForm } from './commit-form'
afterEach(() => { cleanup(); vi.resetAllMocks() })
it('keeps entered values after a rejected save', async () => {
  submit.mockResolvedValue({ error: 'Synthetic rejected forecast' })
  render(<CommitForm defaultPeriod="2026-11" />)
  fireEvent.change(screen.getByLabelText(/Commit amount/), { target: { value: '500' } })
  fireEvent.change(screen.getByLabelText('Notes'), { target: { value: 'Keep this draft' } })
  fireEvent.click(screen.getByRole('button', { name: 'Submit forecast' }))
  expect(await screen.findByText('Synthetic rejected forecast')).toBeVisible()
  expect(screen.getByLabelText(/Commit amount/)).toHaveValue(500)
  expect(screen.getByLabelText('Notes')).toHaveValue('Keep this draft')
})
it('recovers an uncertain response through a read without automatically submitting again', async () => {
  submit.mockRejectedValue(new Error('Synthetic lost response'))
  render(<CommitForm defaultPeriod="2026-11" />)
  fireEvent.change(screen.getByLabelText(/Commit amount/), { target: { value: '500' } })
  fireEvent.click(screen.getByRole('button', { name: 'Submit forecast' }))
  await waitFor(() => expect(screen.getByRole('link', { name: 'Reload saved forecast' })).toHaveAttribute('href', '/forecast'))
  expect(screen.getByRole('button', { name: 'Submit forecast' })).toBeDisabled()
  expect(submit).toHaveBeenCalledTimes(1)
})
it('blocks retry when the server returns an uncertain persistence result', async () => {
  submit.mockResolvedValue({ error: 'Could not confirm save', uncertain: true })
  render(<CommitForm defaultPeriod="2026-11" />)
  fireEvent.change(screen.getByLabelText(/Commit amount/), { target: { value: '500' } })
  fireEvent.click(screen.getByRole('button', { name: 'Submit forecast' }))
  expect(await screen.findByText('Could not confirm save')).toBeVisible()
  expect(screen.getByRole('link', { name: 'Reload saved forecast' })).toHaveAttribute('href', '/forecast')
  expect(screen.getByRole('button', { name: 'Submit forecast' })).toBeDisabled()
  expect(submit).toHaveBeenCalledTimes(1)
})
it('keeps the confirmed receipt if a UI follow-up fails', async () => {
  submit.mockResolvedValue({ data: { id: 'saved' } })
  render(<CommitForm defaultPeriod="2026-11" onSuccess={() => { throw new Error('Synthetic UI failure') }} />)
  fireEvent.change(screen.getByLabelText(/Commit amount/), { target: { value: '500' } })
  fireEvent.click(screen.getByRole('button', { name: 'Submit forecast' }))
  expect(await screen.findByText('Forecast submitted.')).toBeVisible()
  expect(screen.queryByRole('link', { name: 'Reload saved forecast' })).not.toBeInTheDocument()
  expect(submit).toHaveBeenCalledTimes(1)
})
